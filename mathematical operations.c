#include<stdio.h>
#include<stdlib.h>
#include<math.h>
int main(){
    printf("ceil: %2f\n", ceil(44.21));
    printf("floor: %2f\n", floor(44.21));
    printf("round: %2f\n", round(44.21));
    printf("pow: %2f\n", pow(4,2));
    printf("square root: %2f\n", sqrt(44.21));
    printf("absolute: %d\n", abs(44.21));
}